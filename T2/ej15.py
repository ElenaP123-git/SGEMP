numeros = [10, 20, 30, 40, 50, 60, 70, 80]

# 1. Los tres primeros valores
print("Tres primeros:", numeros[:3])

# 2. Los tres últimos
print("Tres últimos:", numeros[-3:])

# 3. Los valores desde 30 hasta 60 (índices del 2 al 5)
print("De 30 a 60:", numeros[2:6])

# 4. Elementos en posiciones pares (índices 0, 2, 4, 6)
print("Posiciones pares:", numeros[::2])